"""Artifact rendering and persistence for ``maverick critique``.

Schema: ``specs/058-standalone-code-review/contracts/critique-report-schema.md``.

Mirrors ``assumptions/land_report.py``'s persistence contract deliberately:
same atomic writers, same json+md pair, same "persistence failure is the
caller's warning, never a gate failure" split (FR-018). The markdown is a
rendering of the *same* projection the JSON carries, so the two can never
disagree about what was found.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from maverick.critique.models import counts_summary
from maverick.utils.atomic import atomic_write_json, atomic_write_text

if TYPE_CHECKING:
    from pathlib import Path

    from maverick.critique.models import CritiqueReport

__all__ = ["persist_report", "render_markdown", "report_paths"]


def report_paths(run_id: str, *, cwd: Path) -> tuple[Path, Path]:
    """Return the ``(json, md)`` artifact paths for *run_id*."""
    run_dir = cwd / ".maverick" / "runs" / run_id
    return run_dir / "critique-report.json", run_dir / "critique-report.md"


def persist_report(report: CritiqueReport, *, cwd: Path) -> tuple[Path, Path]:
    """Write the json+md artifact pair.

    Args:
        report: The completed critique.
        cwd: The checkout — the run directory hangs off it.

    Returns:
        ``(json_path, md_path)``.

    Raises:
        OSError: The write failed. Callers degrade this to a warning and set
            ``degraded_persistence`` — a report that could not be filed is
            still a report that was produced (FR-018).
    """
    json_path, md_path = report_paths(report.run_id, cwd=cwd)
    atomic_write_json(json_path, report.to_dict())
    atomic_write_text(md_path, render_markdown(report))
    return json_path, md_path


def render_markdown(report: CritiqueReport) -> str:
    """Render *report* as markdown, suitable for `gh pr create --body-file`."""
    from maverick import __version__

    lines: list[str] = ["# Code review findings", ""]
    lines.append(f"**Scope**: {report.scope.summary}")
    lines.append(f"**Run**: `{report.run_id}`")
    lines.append(f"**Generated**: {report.created_at}")
    lines.append("")

    if not report.reviewed:
        lines.append("Nothing to review — the scope was empty.")
        lines.append("")
        lines.append(f"Generated by maverick critique {__version__}")
        return "\n".join(lines)

    if report.scope.commits:
        lines.append("## Commits reviewed")
        lines.append("")
        for commit in report.scope.commits:
            attributed = ", ".join(commit.bead_ids)
            lines.append(f"- `{commit.sha}` {commit.subject} ({attributed})")
        lines.append("")

    if report.truncated:
        lines.append(
            "> The embedded diff was truncated at the budget; the reviewer "
            "received the complete file list and read the remainder directly."
        )
        lines.append("")

    for lens in report.lens_failures:
        lines.append(f"> The {lens.lens} lens failed: {lens.error}")
        lines.append("")

    if not report.findings:
        lines.append("No findings.")
        lines.append("")
    else:
        total = len(report.findings)
        plural = "" if total == 1 else "s"
        lines.append(f"## {total} finding{plural} — {counts_summary(report.severity_counts)}")
        lines.append("")
        for name, findings in report.findings_by_file():
            lines.append(f"### {name or '(unattributed)'}")
            lines.append("")
            for finding in findings:
                location = f"L{finding.line}" if finding.line is not None else "—"
                lens_name = f" _{finding.reviewer}_" if finding.reviewer else ""
                lines.append(f"- **{finding.severity}** ({location}){lens_name} — {finding.issue}")
            lines.append("")

    lines.append(f"Generated by maverick critique {__version__}")
    return "\n".join(lines)
